import { describe, expect, it } from "vitest";
import { normalizePhone } from "./phone.ts";

describe("normalizePhone (#114)", () => {
  it.each([
    ["+375291112233", "+375291112233"],
    ["+375 29 111-22-33", "+375291112233"],
    ["+375 (29) 111 22 33", "+375291112233"],
    ["375291112233", "+375291112233"],
    ["80291112233", "+375291112233"],
    ["8 029 111-22-33", "+375291112233"],
    ["291112233", "+375291112233"],
    // Префикс поля «+375» и номер, вставленный целиком.
    ["+375+375291112233", "+375291112233"],
    ["+375+375 29 111-22-33", "+375291112233"],
    ["+375375291112233", "+375291112233"],
    ["+3758 029 111-22-33", "+375291112233"],
    ["+37580291112233", "+375291112233"],
  ])("%s → %s", (input, expected) => {
    expect(normalizePhone(input)).toBe(expected);
  });

  it("не белорусский номер — как введён, без префикса поля", () => {
    expect(normalizePhone("+7 916 123-45-67")).toBe("+79161234567");
    expect(normalizePhone("+375+7 916 123-45-67")).toBe("+79161234567");
  });

  it("неполный номер не дополняется — его отклонит проверка формата", () => {
    expect(normalizePhone("+375")).toBe("+375");
    expect(normalizePhone("+375 29 111")).toBe("+37529111");
  });
});
